"""Generate a shim DLL's export table from the WINAPI functions in its sources.

Usage: gen_exports.py <symbol> <dll-name> <output.c> <source.c>...
"""
import re
import sys

sym, dll, out, *sources = sys.argv[1:]
names = []
for src in sources:
    text = open(src).read()
    # Exported functions are the non-static WINAPI definitions.
    for m in re.finditer(r'^(?!static)[^\n;()]*\bWINAPI\s+\**(\w+)\s*\(', text, re.M):
        names.append(m.group(1))
# An optional "// ordinal: Name N" comment assigns ordinals for DLLs imported by number.
ordinals = {}
for src in sources:
    for m in re.finditer(r'//\s*ordinal:\s*(\w+)\s+(\d+)', open(src).read()):
        ordinals[m.group(1)] = int(m.group(2))

with open(out, 'w') as f:
    f.write('// Generated by tools/gen_exports.py. Do not edit.\n#include "win32.h"\n\n')
    for n in names:
        f.write(f'void {n}(void);\n')
    f.write(f'\nconst struct shim_export {sym}[] = {{\n')
    for n in names:
        f.write(f'    {{"{n}", {ordinals.get(n, 0)}, (void *){n}}},\n')
    f.write('    SHIM_END,\n};\n')
